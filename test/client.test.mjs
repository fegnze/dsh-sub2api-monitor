import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
test('header-only popup sorts accounts and closes only on outside click or Escape', async () => {
  const source = await readFile(new URL('../src/client.js', import.meta.url), 'utf8');
  const entries = [], effects = [], cleanups = [], handlers = new Map();
  let plugin, open = true, navigated;
  const inside = {};
  const React = { createElement: (tag, props, ...children) => ({ tag, props, children }), useState: () => [open, v => { open = v; }], useSyncExternalStore: (_, get) => get(), useRef: () => ({ current: { contains: target => target === inside } }), useEffect: fn => { const cleanup = fn(); if (cleanup) cleanups.push(cleanup); } };
  const accounts = [{ id: 1, status: 'inactive', schedulable: true }, { id: 2, status: 'active', schedulable: true }, { id: 3, status: 'active', schedulable: false }, { id: 4, status: 'active', schedulable: true }];
  const style = { dataset: {}, remove() {} };
  const sandbox = { window: { __ModuleLoader__: { load: d => { plugin = d.factory(() => React); } } }, document: { createElement: () => style, head: { appendChild() {} }, addEventListener: (name, fn) => handlers.set(name, fn), removeEventListener: name => handlers.delete(name) }, AbortController, AbortSignal, setInterval: () => 1, clearInterval() {}, fetch: async () => ({ ok: true, json: async () => ({ accounts, stale: false }) }) };
  vm.runInNewContext(source, sandbox);
  plugin.apply({ pluginNavigation: { openBundle: name => { navigated = name; } }, effect: fn => effects.push(fn()), slots: { inject: (_, fn) => fn(), register: (options, component) => { entries.push({ options, component }); return () => {}; } } });
  assert.deepEqual(entries.map(e => e.options.name), ['plugins.bundle.config', 'conversation.session.header.utilities']);
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(entries[0].options.key, 'dsh-sub2api-monitor');
   const summary = entries[1].component();
  const popup = summary.children[1];
  const panel = popup.tag(popup.props);
  assert.equal(panel.props.className, 's2m s2m-dialog');
  const grid = panel.children.find(child => child?.props?.className === 's2m-grid');
  assert.equal(grid.children.map(child => child.props.a.id).join(','), '2,4,1,3');
  assert.equal(accounts.map(a => a.id).join(','), '1,2,3,4');
  const Card = grid.children[0].tag;
  for (const [utilization, expected] of [[30, '剩余 70%'], [87, '剩余 13%'], [110, '剩余 0%'], [null, '剩余未知']]) {
    const card = Card({ a: { windows: [{ key: 'five_hour', utilization, resetsAt: '2099-01-01T00:00:00Z' }] } });
    const window = card.children[3][0];
    const details = window.children[2];
    assert.equal(details.props.className, 's2m-row');
    assert.equal(details.children[0].children[0], expected);
    assert.match(details.children[1].children[0], /后重置/);
    assert.equal(details.children[0].props.className, utilization >= 95 ? 'danger' : utilization >= 80 ? 'warn' : '');
  }
  const configure = panel.children[0].children.find(child => child?.props?.['aria-label'] === '插件信息与配置');
   configure.props.onClick(); assert.equal(navigated, 'dsh-sub2api-monitor'); assert.equal(open, false); open = true;
   handlers.get('pointerdown')({ target: inside }); assert.equal(open, true);
  handlers.get('pointerdown')({ target: {} }); assert.equal(open, false);
  open = true; handlers.get('keydown')({ key: 'Escape' }); assert.equal(open, false);
  cleanups.forEach(fn => fn()); assert.equal(handlers.size, 0);
  assert.ok(style.textContent.includes('width:min(700px,calc(100vw - 32px))'));
  effects.forEach(fn => fn());
  assert.equal(source.includes('apiKey'), false);
});
