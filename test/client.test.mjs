import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
test('client registers additive slots and renders without secret access', async () => {
  const source = await readFile(new URL('../src/client.js', import.meta.url), 'utf8');
  const entries = [], effects = [], removed = [];
  let plugin, selectedPanel;
  const React = { createElement: (tag, props, ...children) => ({ tag, props, children }), useState: v => [v, () => {}], useSyncExternalStore: (_, get) => get(), useRef: () => ({ current: null }), useEffect: () => {} };
  const accounts = [{ id: 1, status: 'inactive', schedulable: true }, { id: 2, status: 'active', schedulable: true }, { id: 3, status: 'active', schedulable: false }, { id: 4, status: 'active', schedulable: true }];
  const style = { dataset: {}, remove: () => removed.push(true) };
  const sandbox = { window: { __ModuleLoader__: { load: d => { plugin = d.factory(() => React); } } }, document: { createElement: () => style, head: { appendChild() {} } }, AbortController, AbortSignal, setInterval: () => 1, clearInterval() {}, fetch: async () => ({ ok: true, json: async () => ({ accounts, stale: false }) }) };
  vm.runInNewContext(source, sandbox);
  plugin.apply({ layout: { selectPanel: id => { selectedPanel = id; } }, effect: fn => effects.push(fn()), slots: { inject: (_, fn) => fn(), register: (options, component) => { entries.push({ options, component }); return () => {}; } } });
  assert.equal(entries.length, 4);
  assert.deepEqual(entries.map(e => e.options.name), ['sidebar.footer.action', 'shell.overlay', 'main', 'conversation.session.header.utilities']);
  await new Promise(resolve => setImmediate(resolve));
  const panel = entries[2].component({});
  assert.equal(panel.tag, 'section');
  const grid = panel.children.find(child => child?.props?.className === 's2m-grid');
  assert.equal(grid.children.map(child => child.props.a.id).join(','), '2,4,1,3');
  assert.equal(accounts.map(a => a.id).join(','), '1,2,3,4');
  assert.equal(entries[3].component().tag, 'div');
  assert.equal(entries[3].options.order, -30);
  const nav = entries[0].component({ wide: true });
  assert.equal(nav.children[1].children[0], '账号用量');
  nav.props.onClick(); assert.equal(selectedPanel, undefined);
  const modal = entries[1].component();
  assert.equal(modal.tag, 'dialog');
  assert.equal(modal.children[0].props.modal, true);
  modal.props.onCancel();
  assert.equal(entries[1].component().children[0], null);
  assert.equal(entries[0].component({ wide: false }).children[1], null);
  assert.equal(entries[2].component({ popup: true, footer: true }).props.className, 's2m s2m-dialog s2m-footer-dialog');
  assert.equal(entries[2].component({ popup: true }).props.className, 's2m s2m-dialog');
  assert.ok(style.textContent.includes('width:min(620px,calc(100vw - 32px))'));
  assert.ok(style.textContent.includes('.s2m-dialog .s2m-card{padding:13px'));
  assert.equal(style.dataset.plugin, 'myspace-sub2api-monitor');
  effects.forEach(fn => fn()); assert.equal(removed.length, 1);
  assert.equal(source.includes('apiKey'), false);
});
